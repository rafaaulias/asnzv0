const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, id };

let language: Language = 'en';
const listeners = new Set<() => void>();

export function getLanguage() {
  return language;
}

export function setLanguage(next: Language) {
  language = next;
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useTranslation() {
  useSyncExternalStore(subscribe, getLanguage);
  const t = (key: TranslationKey) => dictionaries[language][key];
  const dayLabels = language === 'id'
    ? ['Mi', 'Se', 'Sl', 'Ra', 'Ka', 'Jm', 'Sa']
    : ['Su', 'Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa'];
  const weekLabels = language === 'id'
    ? ['Sen', 'Sel', 'Rab', 'Kam', 'Jum', 'Sab', 'Min']
    : ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  return { t, language, dayLabels, weekLabels };
}

